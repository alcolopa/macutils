import AppKit

/// Remembers recently copied text, newest first. History lives in memory only (it is never written to
/// disk), and copies flagged as concealed/transient by password managers are skipped.
@MainActor
public final class ClipboardStore {
    public static let shared = ClipboardStore()
    
    public static let maxItems = 30
    private static let maxLength = 100_000
    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]
    
    public private(set) var items: [String] = []
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    
    private init() {}
    
    public func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        capture()
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }
    
    public func stop() {
        timer?.invalidate()
        timer = nil
    }
    
    public func clear() { items.removeAll() }
    
    /// Writes `text` to the system pasteboard without it being treated as a new copy, and moves it to the top.
    public func writeToPasteboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
        insert(text)
    }
    
    private func poll() {
        let count = NSPasteboard.general.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture()
    }
    
    private func capture() {
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0) }),
              let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxLength else { return }
        insert(text)
    }
    
    private func insert(_ text: String) {
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
    }
}
