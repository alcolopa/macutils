import AppKit

/// Remembers recently copied items, newest first. History lives in memory only (it is never written to
/// disk), and copies flagged as concealed/transient by password managers are skipped.
@MainActor
public final class ClipboardStore {
    public static let shared = ClipboardStore()
    public static let didChange = Notification.Name("MacUtilsClipboardDidChange")
    
    private static let maxTextLength = 200_000
    private static let maxImageBytes = 15_000_000
    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]
    
    public private(set) var items: [ClipboardItem] = []
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    
    private init() {}
    
    public func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        capture()
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }
    
    public func stop() {
        timer?.invalidate()
        timer = nil
    }
    
    public var isRunning: Bool { timer != nil }
    
    public func clear() {
        items.removeAll()
        NotificationCenter.default.post(name: Self.didChange, object: nil)
    }
    
    /// Writes `item` to the system pasteboard without it being treated as a new copy, and moves it to the top.
    public func writeToPasteboard(_ item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.content {
        case .text(let t): pb.setString(t, forType: .string)
        case .image(let data, _):
            if let image = NSImage(data: data) { pb.writeObjects([image]) } else { pb.setData(data, forType: .png) }
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pb.changeCount
        insert(item)
    }
    
    /// Drops the oldest entries when the history limit has been lowered.
    public func trimToLimit() {
        let limit = AppPreferences.shared.clipboardMaxItems
        if items.count > limit {
            items.removeLast(items.count - limit)
            NotificationCenter.default.post(name: Self.didChange, object: nil)
        }
    }
    
    private func poll() {
        let count = NSPasteboard.general.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !AppPreferences.shared.clipboardPaused else { return }
        capture()
    }
    
    private func capture() {
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0) }) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let rich = AppPreferences.shared.clipboardCaptureRich
        
        if rich,
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(ClipboardItem(content: .files(urls), sourceBundleID: source))
        } else if let text = pb.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxTextLength else { return }
            insert(ClipboardItem(content: .text(text), sourceBundleID: source))
        } else if rich, let png = Self.pngData(from: pb), png.0.count <= Self.maxImageBytes {
            insert(ClipboardItem(content: .image(png.0, png.1), sourceBundleID: source))
        }
    }
    
    private static func pngData(from pb: NSPasteboard) -> (Data, NSSize)? {
        if let png = pb.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            return (png, NSSize(width: rep.pixelsWide, height: rep.pixelsHigh))
        }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return (png, NSSize(width: rep.pixelsWide, height: rep.pixelsHigh))
    }
    
    private func insert(_ item: ClipboardItem) {
        items.removeAll { $0.key == item.key }
        items.insert(item, at: 0)
        let limit = AppPreferences.shared.clipboardMaxItems
        if items.count > limit { items.removeLast(items.count - limit) }
        NotificationCenter.default.post(name: Self.didChange, object: nil)
    }
}
